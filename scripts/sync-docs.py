#!/usr/bin/env python3
"""Import the ADT (Qt) website content from the README and embedded guide."""

import argparse
import os
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "docs/site"
PUBLIC = SITE / "public"
GUIDE_SOURCE = "src/adt_help.cc"
GUIDE_ROUTES = {
    "Getting Started": "/get-started/first-display",
    "Display Areas": "/operate/display-areas",
    "Log Scale": "/operate/log-scale",
    "Zoom Area": "/operate/zoom-area",
    "Status Checking": "/operate/status",
    "Stored Sets, References and Differences": "/operate/stored-sets",
    "Snapshots and Plots": "/operate/snapshots-plots",
    "PV Files": "/reference/pv-files",
    "Configuration File": "/reference/configuration",
    "Command-Line Options": "/reference/command-line",
    "Differences from Motif ADT": "/understand/legacy-differences",
    "Keyboard Shortcuts": "/reference/keyboard-shortcuts",
}
README_ROUTES = {
    "Building": "/get-started/install",
    "Starting ADT": "/reference/startup",
    "Configuration File": "/reference/configuration-details",
    "Qt behavior and the historical manual": "/understand/qt-behavior",
}
GENERATED_PAGES = tuple(
    route.lstrip("/") + ".md"
    for route in (*GUIDE_ROUTES.values(), *README_ROUTES.values(), "/project/license")
)
GENERATED_FILES = (*GENERATED_PAGES, "_includes/version.md")


def read(name):
    return (ROOT / name).read_text(encoding="utf-8")


def anchor(title):
    return re.sub(r"\s+", "-", re.sub(r"[^\w\s-]", "", title.lower()))


def version():
    header = read("src/adtVersion.h")
    names = ("VERSION", "REVISION", "MODIFICATION", "PATCH_LEVEL")
    parts = []
    for name in names:
        match = re.search(r"^#define\s+ADT_" + name + r"\s+(\d+)\s*$", header, re.MULTILINE)
        if not match:
            raise ValueError(f"Missing ADT_{name} in src/adtVersion.h")
        parts.append(match.group(1))
    return ".".join(parts)


def guide_sections():
    source = read(GUIDE_SOURCE)
    table = re.search(
        r"const GuideSection guideSections\[\]\s*=\s*\{(.*?)^\};",
        source, re.DOTALL | re.MULTILINE,
    )
    if not table:
        raise ValueError("Cannot find guideSections in src/adt_help.cc")
    sections = re.findall(r'\{\s*"([^"]+)",\s*R"md\((.*?)\)md"\s*\}', table.group(1), re.DOTALL)
    if [title for title, _ in sections] != list(GUIDE_ROUTES):
        raise ValueError(
            "Embedded guide headings changed. Update GUIDE_ROUTES, navigation, and docs/site/.gitignore."
        )
    return [(title, body.strip()) for title, body in sections]


def guide_markdown(sections):
    intro = f"# ADT (Qt) user guide\n\nDocumentation for ADT (Qt) {version()}.\n"
    return intro + "".join(f"\n## {title}\n\n{body}\n" for title, body in sections)


def rewrite(text, source):
    """Resolve imported guide fragments and repository-document links."""
    def link(match):
        label, target = match.groups()
        if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", target) or target.startswith("/"):
            return match.group(0)
        if source == GUIDE_SOURCE and target.startswith("#"):
            routes = {anchor(title): route for title, route in GUIDE_ROUTES.items()}
            fragment = target[1:]
            if fragment not in routes:
                raise ValueError(f"Unknown embedded guide link {target}")
            return f"[{label}]({routes[fragment]}#{fragment})"
        if source == "README.md":
            routes = {
                "doc/adt.html": "https://ops.aps.anl.gov/manuals/adt/adt.html",
                "docs/site/develop/documentation.md": "/develop/documentation",
            }
            if target in routes:
                return f"[{label}]({routes[target]})"
        if target.startswith("#"):
            return match.group(0)
        raise ValueError(f"Unregistered documentation link in {source}: {target}")
    return re.sub(r"(?<!!)\[([^\]]+)\]\(([^)]+)\)", link, text)


def write_page(route, title, body, source):
    path = SITE / (route.lstrip("/") + ".md")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"<!-- Generated by scripts/sync-docs.py from {source}. Edit that source. -->\n\n"
        f"# {title} {{#{anchor(title)}}}\n\n{body.strip()}\n",
        encoding="utf-8",
    )


def synchronize():
    os.umask(0o022)
    sections = guide_sections()
    ignored = read("docs/site/.gitignore").splitlines()
    if any("/" + name not in ignored for name in GENERATED_FILES):
        raise ValueError("Register all generated files in docs/site/.gitignore")
    for title, body in sections:
        write_page(GUIDE_ROUTES[title], title, rewrite(body, GUIDE_SOURCE), GUIDE_SOURCE)
    parts = re.split(r"^## (.+)\n", read("README.md"), flags=re.MULTILINE)
    readme = dict(zip(parts[1::2], parts[2::2]))
    for title, route in README_ROUTES.items():
        if title not in readme:
            raise ValueError(f"Missing README section {title}")
        write_page(route, title, rewrite(readme[title], "README.md"), "README.md")
    write_page("/project/license", "License", "```text\n" + read("LICENSE").rstrip() + "\n```", "LICENSE")
    fragment = SITE / "_includes/version.md"
    fragment.parent.mkdir(parents=True, exist_ok=True)
    fragment.write_text(
        f"Documentation for **ADT (Qt) {version()}**. The Qt application runs as `adt`.\n",
        encoding="utf-8",
    )
    downloads = PUBLIC / "downloads"
    if downloads.exists():
        shutil.rmtree(downloads)
    downloads.mkdir(parents=True, exist_ok=True)
    (downloads / "adt-qt-guide.md").write_text(guide_markdown(sections), encoding="utf-8")
    (downloads / "README.md").write_bytes((ROOT / "README.md").read_bytes())
    print(f"Imported all {len(sections)} guide topics and {len(README_ROUTES)} README sections.")


def clean(dependencies=False):
    paths = [SITE / name for name in GENERATED_FILES]
    paths += [PUBLIC / "downloads", SITE / ".vitepress/cache", SITE / "dist", ROOT / "docs/html"]
    if dependencies:
        paths.append(SITE / "node_modules")
    for path in paths:
        if path.is_symlink() or path.is_file():
            path.unlink()
        elif path.is_dir():
            shutil.rmtree(path)
    print("Removed generated documentation" + (" and npm dependencies." if dependencies else "."))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--clean", action="store_true")
    modes.add_argument("--distclean", action="store_true")
    args = parser.parse_args()
    if args.clean or args.distclean:
        clean(dependencies=args.distclean)
    else:
        synchronize()


if __name__ == "__main__":
    main()
